    _pscad_attributes!(station,
        (
            link = _PSCAD_IDS.station,
            name = "$namespace:DS",
            z = -1,
            view = "false",
            instance = 0
        ))
    main = addelement!(station, "call")
    _pscad_attributes!(main,
        (
            link = _PSCAD_IDS.main_instance,
            name = "$namespace:Main",
            z = -1,
            view = "false",
            instance = 0
        ))
