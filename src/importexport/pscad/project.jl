function _pscad_project_scaffolding!(project)
    addelement!(project, "Layers")
    addelement!(project, "List")["classid"] = "Settings"
    addelement!(project, "bookmarks")
    substitutions = addelement!(project, "GlobalSubstitutions")
    substitutions["name"] = "Default"
    addelement!(substitutions, "List")["classid"] = "Sub"
    addelement!(substitutions, "List")["classid"] = "ValueSet"
    _pscad_paramlist!(substitutions, ["Current" => ""])
    return project
end

