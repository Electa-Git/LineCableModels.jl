            dielectric_ranges = [1:6, 7:8, 9:9, 10:15, 16:17, 18:18, 19:24, 25:26, 27:27],
            assemblies = [1:3, 4:6, 7:9],
            members = [Int[], Int[], Int[]],
            enclosed = [1:3, 4:6, 7:9],
            interior_ranges = [1:0, 10:9, 19:18],
            exterior_ranges = [1:0, 1:0, 1:0],
            earth_layer = [2, 2, 2],
            bundles = Tuple{Int, Int}[],
            kept = [1, 2, 3, 4, 5, 6, 7, 8, 9],
            eliminated = Int[],
            terminals = ["cable:1:core", "cable:1:sheath", "cable:1:jacket",
                "cable:2:core", "cable:2:sheath", "cable:2:jacket",
                "cable:3:core", "cable:3:sheath", "cable:3:jacket"]
        )
    ]
    options = LineCableModels.FormulationOptions(CoaxialFormulation)
    references = Dict(REFERENCES)
    properties = (:rho, :eps_r, :mu_r, :T0, :alpha, :tan_delta)

    @testset "$case" for (case, record) in records
        problem = haskey(references, case) ? references[case] :
                  include(joinpath(@__DIR__, case, "problem.jl"))
        input = LineCableModels.Engine.CoaxialInput(problem, options)
        tubes = hcat(input.r_in, input.r_ex,
            [getfield(tube, property) for tube in input.material, property in properties])
        layers = hcat(input.dielectric_r_in, input.dielectric_r_ex,
            [getfield(layer, property)
             for layer in input.dielectric_material, property in properties])
        # Each radius and each property lies within 1e-12 of its value of record.
        @test all(isapprox.(tubes, record.tubes; rtol = 1.0e-12))
        @test all(isapprox.(layers, record.layers; rtol = 1.0e-12))
        @test all(layer isa Material{Float64, kind}
        for (layer, kind) in zip(input.dielectric_material, record.kinds))
        for field in (:r_ins_ex, :mu_r_ins, :radius)
            @test all(isapprox.(getfield(input, field), getfield(record, field);
                rtol = 1.0e-12))
        end
        # Each coordinate lies within 1e-12 of the largest coordinate of record, since a
        # coordinate on an axis of the frame is a rounding residue.
        for (computed, target) in (
            ([position[i] for position in input.positions, i in 1:2], record.positions),
            (hcat(input.x, input.y), record.centers))
            @test all(isapprox.(computed, target;
                rtol = 0, atol = 1.0e-12 * maximum(abs, target)))
        end
        for field in (:cable, :connection, :label, :dielectric_ranges, :assemblies,
            :members, :enclosed, :interior_ranges, :exterior_ranges, :earth_layer,
            :bundles, :kept, :eliminated, :terminals)
            @test getfield(input, field) == getfield(record, field)
        end
    end
