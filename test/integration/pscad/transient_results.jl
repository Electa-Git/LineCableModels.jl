@testitem "PSCAD / transient channels and terminal response" tags=[:integration, :pscad] setup=[TestFixtures] begin
    const P = LineCableModels.PSCAD
    directory = joinpath(@__DIR__, "..", "..", "fixtures", "pscad", "transient")
    record = P.read_pscad_transient(directory; stem = "channels")
    @test record.time == collect(0:19) ./ 1000
    @test Set(keys(record.channels)) == Set(("sending:cable:1:core:v",
        "sending:cable:1:core:i", "receiving:cable:1:sheath:v",
        "sending:cable:1:sheath:v", "receiving:cable:1:core:v"))
    @test record.channels["sending:cable:1:core:v"] == collect(0:19) .* 10
    @test record.channels["sending:cable:1:core:i"] == collect(0:19) ./ 2
    @test record.channels["receiving:cable:1:sheath:v"] == 100 .- collect(0:19)
    mktempdir() do destination
        cp(joinpath(directory, "channels.inf"), joinpath(destination, "channels.inf"))
        lines = readlines(joinpath(directory, "channels_01.out"))
        @test first(lines) == "Generated by LineCableModels.jl"
        path = joinpath(destination, "channels_01.out")
        write(path, join(lines[2:end], '\n') * "\n")
        @test P.read_pscad_transient(destination; stem = "channels") == record
        write(path, "Generated by LineCableModels.jl\n0.0 invalid 0.0 100.0 20.0 200.0\n")
        @test_throws ArgumentError P.read_pscad_transient(destination; stem = "channels")
    end
    design = TestFixtures.coaxial_design()
    system = build(LineCableSystem, [design], [(0.0, -1.0)];
        connections = [Dict(:core => 1, :sheath => 2)], line_length = 600.0)
    line = LineParametersProblem(system; earth_props = homogeneous(rho = 100.0),
        frequencies = [1.0, 1e6])
    problem = TransientAnalysisProblem(line; sending = (Step("cable:1:core", 190.0),),
        receiving = (), window = (tmax = 0.019, step = 0.001))
    response = P.read_pscad_transient(record, problem)
    voltage = zeros(2, 2, 20)
    current = zeros(2, 2, 20)
    voltage[1, 1, :] = collect(0:19) .* 10
    voltage[1, 2, :] = 20 .+ collect(0:19)
    voltage[2, 1, :] = 200 .+ 2 .* collect(0:19)
    voltage[2, 2, :] = 100 .- collect(0:19)
    current[1, 1, :] = collect(0:19) ./ 2
    @test response.t == record.time
    @test response.coordinates == ["cable:1:core", "cable:1:sheath"]
    @test response.voltage == voltage
    @test response.current == current
    for name in keys(record.channels)
        channels = copy(record.channels)
        delete!(channels, name)
        @test_throws "missing PSCAD channel $name" P.read_pscad_transient(
            (time = record.time, channels), problem)
    end
    matched = TransientAnalysisProblem(line; sending = problem.sending,
        receiving = Matched(), window = problem.window)
    channels = copy(record.channels)
    channels["receiving:cable:1:core:i"] = fill(2.0, 20)
    channels["receiving:cable:1:sheath:i"] = fill(-3.0, 20)
    matched_record = (time = record.time, channels)
    @test P.read_pscad_transient(matched_record, matched).voltage == voltage
    current[2, 1, :] .= 2.0
    current[2, 2, :] .= -3.0
    @test P.read_pscad_transient(matched_record, matched).current == current
    for name in keys(channels)
        incomplete = copy(channels)
        delete!(incomplete, name)
        @test_throws "missing PSCAD channel $name" P.read_pscad_transient(
            (time = record.time, channels = incomplete), matched)
    end
end

@testitem "PSCAD / nonfinite transient samples retain channel and time" tags=[:integration, :pscad] begin
    const P = LineCableModels.PSCAD
    fixture = joinpath(@__DIR__, "..", "..", "fixtures", "pscad", "transient")
    caught = try
        P.read_pscad_transient(fixture; stem = "nonfinite")
    catch error
        error
    end
    @test caught isa P.NonfiniteOutputError
    @test caught.output_path == joinpath(fixture, "nonfinite_02.out")
    @test caught.channel == "receiving:cable:1:core:v"
    @test caught.time == 0.001
    @test occursin(caught.output_path, sprint(showerror, caught))
    @test occursin(caught.channel, sprint(showerror, caught))
    @test occursin("t=0.001 s", sprint(showerror, caught))
    mktempdir() do directory
        for name in ("nonfinite.inf", "nonfinite_01.out", "nonfinite_02.out")
            cp(joinpath(fixture, name), joinpath(directory, name))
        end
        write(joinpath(directory, "pscad-console.txt"), "fixture")
        write(joinpath(directory, "timing.txt"), "0.1")
        write(joinpath(directory, "execution.toml"), "mode = 'transient'")
        @test_throws P.NonfiniteOutputError P.validate(directory,
            P.PSCADTransientFormulation(); output_stem = "nonfinite")
        first_path = joinpath(directory, "nonfinite_01.out")
        second_path = joinpath(directory, "nonfinite_02.out")
        write(second_path, replace(read(second_path, String), "Inf" => "1"))
        nan_error = try
            P.read_pscad_transient(directory; stem = "nonfinite")
        catch error
            error
        end
        @test nan_error isa P.NonfiniteOutputError
        @test nan_error.output_path == first_path
        @test nan_error.channel == "receiving:cable:1:sheath:v"
        @test nan_error.time == 0.002
        write(first_path, replace(read(first_path, String), "NaN" => "2"))
        negative_inf = try
            P.read_pscad_transient(directory; stem = "nonfinite")
        catch error
            error
        end
        @test negative_inf isa P.NonfiniteOutputError
        @test negative_inf.channel == "sending:cable:1:core:v"
        @test negative_inf.time == 0.003
        write(first_path, replace(read(first_path, String), "-Inf" => "3"))
        finite = P.read_pscad_transient(directory; stem = "nonfinite")
        @test finite.time == [0.0, 0.001, 0.002, 0.003]
        @test length(finite.channels) == 11
        @test all(values(finite.channels)) do samples
            all(isfinite, samples)
        end
        write(second_path, replace(read(second_path, String), "0.001" => "NaN"))
        @test_throws ArgumentError P.read_pscad_transient(directory; stem = "nonfinite")
        rm(second_path)
        @test_throws ArgumentError P.read_pscad_transient(directory; stem = "nonfinite")
    end
end

